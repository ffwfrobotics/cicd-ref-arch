#!/usr/bin/env bash
# A new instance's platform repo: this product (the paths in product-paths) at the current commit,
# plus the instance's own files: instance.yaml, tenants/_writable.yaml and _limits.yaml, and
# clusters/<CLUSTER>/ (Flux entry, platform layer, environments). No other instance's state (tenants,
# environments, promotions, stacks) comes along.
#   new-instance.sh instances/<name>.env <out dir>
# Upgrading later is the same drop: re-run into a checkout of the instance repo and commit; only
# product paths change (instance.yaml records the product commit it came from).
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd); src=$(cd "$here/.." && pwd)
# shellcheck disable=SC1090
. "$1"; out=$2
mkdir -p "$out"
rev=$(git -C "$src" rev-parse --short HEAD)
git -C "$src" diff --quiet HEAD -- $(cat "$here/product-paths") || echo "warning: product paths have uncommitted changes; using HEAD ($rev)" >&2
for p in $(cat "$here/product-paths"); do rm -rf "${out:?}/$p"; done
git -C "$src" archive HEAD $(cat "$here/product-paths") | tar -x -C "$out"

cat > "$out/instance.yaml" <<EOT
# Who this platform instance is (tools/cicd.py instance()). Made by install/new-instance.sh.
name: $INSTANCE
product: {from: cicd-ref-arch, commit: $rev}
platform_repo: $PLATFORM_REPO
iac_org: $IAC_ORG
tenant: $TENANT
cluster: $CLUSTER
forge_ssh: $FORGE_SSH
compliance_url: https://$FORGE_HOST/$COMPLIANCE_REPO
EOT
mkdir -p "$out/tenants" "$out/envs/$CLUSTER" "$out/promotions/done" "$out/clusters/$CLUSTER"
[ -f "$out/tenants/_writable.yaml" ] || cat > "$out/tenants/_writable.yaml" <<EOT
# The repos CI/CD may write to (docs/enrollment.md, "Who writes where"): its own repos and the IaC repos
# that wrap apps. Every other repo is a developer's: CI/CD reads it and never writes there.
owners: [$IAC_ORG]
repos: [$PLATFORM_REPO, $COMPLIANCE_REPO, ${PLATFORM_REPO%%/*}/cicd-dashboard, ${PLATFORM_REPO%%/*}/cicd-factory]
EOT
[ -f "$out/tenants/_limits.yaml" ] || printf '# Branch environments a tenant may have at once (tools/cicd.py route).\ndefault: 16\n' > "$out/tenants/_limits.yaml"
[ -f "$out/envs/$CLUSTER/kustomization.yaml" ] || printf '# Generated by tools/cicd.py index.\napiVersion: kustomize.config.k8s.io/v1beta1\nkind: Kustomization\nresources: []\n' > "$out/envs/$CLUSTER/kustomization.yaml"
d=$out/clusters/$CLUSTER
if [ ! -f "$d/kustomization.yaml" ]; then    # the instance's own from here on: an upgrade leaves it alone
  sed -e "s#\./envs/c-local#./envs/$CLUSTER#" "$here/cluster/envs.yaml" > "$d/envs.yaml"
  cp "$here/cluster/platform.yaml" "$d/platform.yaml"
  cat > "$d/kustomization.yaml" <<EOT
apiVersion: kustomize.config.k8s.io/v1beta1
kind: Kustomization
resources: [cicd-vars.yaml, platform.yaml, envs.yaml]
EOT
  cat > "$d/cicd-vars.yaml" <<EOT
apiVersion: v1
kind: ConfigMap
metadata: {name: cicd-vars, namespace: flux-system}
data:
  CLUSTER: $CLUSTER
  ZONE: $ZONE
  CLUSTER_ISSUER: $CLUSTER_ISSUER
  REGISTRY_PULL: localhost:5000
  REGISTRY_NODE_PORT: "5000"
  NODE_CIDR: $NODE_CIDR
  RUNNER_NAMESPACE: ci
  RUNNER_APP_LABEL: forgejo-runner
EOT
  sed -e "s#^cluster: .*#cluster: $CLUSTER#; s#^zone: .*#zone: $ZONE#; s#ffwf/cicd-compliance#$COMPLIANCE_REPO#g" \
  "$here/cluster/cicd-cluster.yaml" > "$d/cicd-cluster.yaml"
  cat > "$d/flux-entry.yaml" <<EOT
# Bootstrap, applied once by hand: kubectl apply -f clusters/$CLUSTER/flux-entry.yaml
# Needs Secret flux-system/platform-deploy-key (identity, known_hosts): a read-only deploy key.
apiVersion: source.toolkit.fluxcd.io/v1
kind: GitRepository
metadata: {name: cicd-ref-arch, namespace: flux-system}
spec:
  interval: 1m
  url: $FORGE_SSH/$PLATFORM_REPO.git
  ref: {branch: master}
  secretRef: {name: platform-deploy-key}
---
apiVersion: kustomize.toolkit.fluxcd.io/v1
kind: Kustomization
metadata: {name: cicd, namespace: flux-system}
spec:
  interval: 10m
  retryInterval: 30s
  path: ./clusters/$CLUSTER
  prune: true
  sourceRef: {kind: GitRepository, name: cicd-ref-arch}
EOT
fi
echo "$out: product $rev + instance $INSTANCE (cluster $CLUSTER)"
