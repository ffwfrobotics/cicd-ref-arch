#!/usr/bin/env python3
"""wrap: enroll an app in wrapped mode (docs/enrollment.md). Creates the IaC repo <org>/<app>, with the
source repo as the submodule src/, a Dockerfile, cicd.yaml and deploy/ generated for it, and writes
tenants/<app>.yaml here. Nothing is pushed to the source repo.

  FORGEJO_TOKEN=<owner of the IaC org> [CICD_HOOK_SECRET=...] tools/wrap.py --app mabel --source ffwf/mabel-src \
    [--branch main] [--update follow|pin] [--org ffwf-iac] [--tenant ffwf] [--cluster c-local] \
    [--hook-url https://<dashboard>/hooks/forge] [--requested-by john] [--approved]

The Dockerfile: the source's own if it has one (build context src/, dockerfile src/Dockerfile);
otherwise one picked from what the source holds (templates/iac/dockerfiles): a static site
(index.html in ., public/, site/, dist/ or docs/), Python (requirements.txt or pyproject.toml, with
main.py or app.py), Node (package.json with a start script). None of these: no Dockerfile, and
intake's `dockerfile` check says what to add, in the IaC repo.
"""
from __future__ import annotations

import argparse
import base64
import json
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(HERE))
import cicd    # noqa: E402
import intake  # noqa: E402

TEMPLATES = ROOT / "templates" / "iac"


def detect(src: Path) -> dict:
    """What to build the source with: {kind, port, dockerfile text or None, context, dockerfile path, run_as}."""
    if (src / "Dockerfile").is_file():
        return {"kind": "own", "port": intake.exposed_port(src / "Dockerfile"), "text": None,
                "context": "src", "dockerfile": "src/Dockerfile"}
    for site in (".", "public", "site", "dist", "docs"):
        if (src / site / "index.html").is_file():
            t = (TEMPLATES / "dockerfiles/static.Dockerfile").read_text().replace("{site}", "./" if site == "." else f"{site}/")
            return {"kind": "static", "port": 8080, "text": t, "context": "src", "dockerfile": "Dockerfile", "run_as": 101}
    if (src / "requirements.txt").is_file() or (src / "pyproject.toml").is_file():
        entry = next((e for e in ("main.py", "app.py", "server.py") if (src / e).is_file()), None)
        if entry:
            install = "-r requirements.txt" if (src / "requirements.txt").is_file() else "."
            t = (TEMPLATES / "dockerfiles/python.Dockerfile").read_text().replace("{entry}", entry).replace("{install}", install)
            return {"kind": "python", "port": 8000, "text": t, "context": "src", "dockerfile": "Dockerfile"}
    if (src / "package.json").is_file():
        try:
            pkg = json.loads((src / "package.json").read_text())
        except ValueError:
            pkg = {}
        if (pkg.get("scripts") or {}).get("start"):
            t = (TEMPLATES / "dockerfiles/node.Dockerfile").read_text()
            return {"kind": "node", "port": 3000, "text": t, "context": "src", "dockerfile": "Dockerfile"}
    return {"kind": "none", "port": intake.DEFAULT_PORT, "text": None, "context": "src", "dockerfile": "Dockerfile"}


def generate(work: Path, app: str, source: str, d: dict, update: str) -> list[str]:
    """Write the IaC root's files for a detected source. Returns what was written."""
    out = []
    if d["text"]:
        (work / "Dockerfile").write_text(d["text"])
        out.append(f"Dockerfile ({d['kind']})")
    cfg = intake.default_cicd(app, "main", d["port"], context=d["context"], dockerfile=d["dockerfile"])
    (work / "cicd.yaml").write_text(f"# generated by tools/wrap.py for {source} ({d['kind']}): this repo owns it, edit it here\n"
                                    + yaml.safe_dump(cfg, sort_keys=False))
    out.append("cicd.yaml")
    (work / "deploy").mkdir(exist_ok=True)
    files = intake.default_deploy(app, d["port"])
    if d.get("run_as"):
        dep = yaml.safe_load(files["deployment.yaml"])
        sc = dep["spec"]["template"]["spec"]["securityContext"]
        sc["runAsUser"] = sc["runAsGroup"] = d["run_as"]
        files["deployment.yaml"] = yaml.safe_dump(dep, sort_keys=False)
    for name, text in files.items():
        (work / "deploy" / name).write_text(text)
    out.append("deploy/")
    if (work / "src").is_dir():     # what the source's own deploy files were, so intake can say when they change
        (work / ".wrap").mkdir(exist_ok=True)
        (work / ".wrap" / "source-files.json").write_text(json.dumps(
            {"source": "src", "files": intake.source_files(work / "src")}, indent=2, sort_keys=True) + "\n")
        out.append(".wrap/source-files.json")
    how = "each push to its default branch is committed here and deploys dev" if update == "follow" \
        else "each push opens a PR here; merging it deploys"
    (work / "README.md").write_text((TEMPLATES / "README.md").read_text().format(
        app=app, source=source, update=update, update_how=how))
    out.append("README.md")
    return out


def image_facts(ref: str) -> dict:
    """digest, port and user of an existing image (crane): what a prebuilt app's deploy base needs."""
    dig = subprocess.run(["crane", "digest", "--insecure", ref], capture_output=True, text=True)
    if dig.returncode != 0:
        sys.exit(f"cannot resolve {ref}: {dig.stderr.strip()[-200:]}")
    cfg = subprocess.run(["crane", "config", "--insecure", "--platform", "linux/amd64", ref], capture_output=True, text=True)
    c = (json.loads(cfg.stdout or "{}").get("config") or {}) if cfg.returncode == 0 else {}
    ports = sorted(int(p.split("/")[0]) for p in (c.get("ExposedPorts") or {}) if p.endswith("/tcp"))
    user = str(c.get("User") or "").split(":")[0]
    return {"digest": dig.stdout.strip(), "port": ports[0] if ports else intake.DEFAULT_PORT,
            "run_as": int(user) if user.isdigit() and int(user) > 0 else None}


def generate_prebuilt(work: Path, app: str, repository: str, tag: str, facts: dict, update: str) -> list[str]:
    cfg = intake.default_cicd(app, "main", facts["port"])
    del cfg["spec"]["build"]
    cfg["spec"]["image"] = {"repository": repository, "tag": tag, "digest": facts["digest"]}
    (work / "cicd.yaml").write_text(f"# generated by tools/wrap.py for the prebuilt image {repository}:{tag}: this repo owns it\n"
                                    "# spec.image.digest is what runs; the platform moves it when the tag moves (docs/enrollment.md)\n"
                                    + yaml.safe_dump(cfg, sort_keys=False))
    (work / "deploy").mkdir(exist_ok=True)
    files = intake.default_deploy(app, facts["port"])
    if facts.get("run_as"):
        dep = yaml.safe_load(files["deployment.yaml"])
        sc = dep["spec"]["template"]["spec"]["securityContext"]
        sc["runAsUser"] = sc["runAsGroup"] = facts["run_as"]
        files["deployment.yaml"] = yaml.safe_dump(dep, sort_keys=False)
    for name, text in files.items():
        (work / "deploy" / name).write_text(text)
    how = "a new digest for the tag is committed here and deploys dev" if update == "follow" else "a new digest opens a PR here"
    (work / "README.md").write_text(f"# {app}: infrastructure\n\nThis repo is how the prebuilt image **{repository}:{tag}** is "
                                    f"deployed on the platform (cicd-ref-arch, docs/enrollment.md, mode `prebuilt`). Nothing is built: "
                                    f"the image is copied by digest, scanned and deployed.\n\nWhen the tag moves, {how} ({update}).\n")
    return ["cicd.yaml", "deploy/", "README.md"]


def wrap_prebuilt(a, root: Path, token: str, hook_secret: str):
    repository, _, tag = a.image.rpartition(":") if ":" in a.image.rsplit("/", 1)[-1] else (a.image, "", "latest")
    facts = image_facts(f"{repository}:{tag}")
    iac = f"{a.org}/{a.app}"
    code, _ = cicd.api("GET", a.server, f"/repos/{iac}", token)
    if code == 404:
        code, out = cicd.api("POST", a.server, f"/orgs/{a.org}/repos", token, {
            "name": a.app, "private": True, "auto_init": False, "default_branch": "main",
            "description": f"How the image {repository}:{tag} is deployed (cicd-ref-arch, prebuilt)"})
        if code not in (200, 201):
            sys.exit(f"could not create {iac}: {code} {out}")
    elif code == 200 and (cicd.api("GET", a.server, f"/repos/{iac}/branches", token)[1] or []):
        sys.exit(f"{iac} exists and has content")
    user = os.environ.get("BOT", "cicd-bot")
    auth = "AUTHORIZATION: basic " + base64.b64encode(f"{user}:{token}".encode()).decode()
    work = Path(tempfile.mkdtemp(prefix=f"wrap-{a.app}-"))
    try:
        def git(*args):
            return subprocess.run(["git", "-c", f"http.extraHeader={auth}", "-c", "user.name=cicd-bot",
                                   "-c", "user.email=cicd-bot@noreply.invalid", "-C", str(work), *args],
                                  capture_output=True, text=True, check=True).stdout.strip()
        git("init", "-q", "-b", "main")
        made = generate_prebuilt(work, a.app, repository, tag, facts, a.update)
        git("add", "-A")
        msg = [f"prebuilt {repository}:{tag}", "", f"Image-Repo: {repository}", f"Image-Tag: {tag}", f"Image-Digest: {facts['digest']}"]
        if a.requested_by:
            msg.append(f"Requested-by: {a.requested_by}")
        git("commit", "-q", "-m", "\n".join(msg))
        git("push", "-q", f"{a.server.rstrip('/')}/{iac}.git", "HEAD:refs/heads/main")
        print(f"pushed {iac}: {repository}:{tag} = {facts['digest'][:19]}, port {facts['port']}; {', '.join(made)}")
    finally:
        shutil.rmtree(work, ignore_errors=True)
    if a.hook_url:
        hooks(a.server, token, a.hook_url, hook_secret, [iac], Path(a.root))
    write_tenant(root, a, {"mode": "prebuilt", "repo": iac, "path": ".", "image": {"update": a.update}},
                 f"Prebuilt image {repository}:{tag}, deployed from {iac}")


def hooks(server: str, token: str, hook_url: str, secret: str, repos: list[str], root: Path = ROOT):
    """Webhooks on CI/CD's own repos. A developer's repo gets its webhook from the developer (the dashboard
    adds it as them when they enroll): the bot only reads it."""
    for repo in repos:
        if not cicd.writable(root, repo):
            print(f"webhook on {repo}: left to its owner (a developer's repo)")
            continue
        cfg = {"url": hook_url, "content_type": "json", "secret": secret}
        code, have = cicd.api("GET", server, f"/repos/{repo}/hooks", token)
        same = [h for h in (have if code == 200 else []) if (h.get("config") or {}).get("url") == hook_url]
        if same:
            code, _ = cicd.api("PATCH", server, f"/repos/{repo}/hooks/{same[0]['id']}", token, {
                "active": True, "events": ["push", "delete"], "branch_filter": "*", "config": cfg})
        else:
            code, _ = cicd.api("POST", server, f"/repos/{repo}/hooks", token, {
                "type": "forgejo", "active": True, "events": ["push", "delete"], "branch_filter": "*", "config": cfg})
        print(f"webhook on {repo}: {code}")


def write_tenant(root: Path, a, spec: dict, note: str):
    spec = {"kind": "App", "tenant": a.tenant, **spec, "clusters": a.cluster or ["c-local"],
            "enrolled": cicd.now_utc().date().isoformat()}
    if not a.approved:
        spec["status"] = "pending"
    if a.requested_by:
        spec["requestedBy"] = a.requested_by
    t = {"apiVersion": cicd.API, "kind": "Tenant", "metadata": {"name": a.app}, "spec": spec}
    cicd.tenant_spec(t)   # checks it
    (root / "tenants").mkdir(exist_ok=True)
    (root / "tenants" / f"{a.app}.yaml").write_text(f"# {note} (docs/enrollment.md)\n" + yaml.safe_dump(t, sort_keys=False))
    print(f"wrote tenants/{a.app}.yaml ({'approved' if a.approved else 'pending'}): commit and push it")


def submodules(gitmodules: str, repo: str) -> dict[str, str]:
    """path -> owner/name, for .gitmodules entries that point at this forge (relative or absolute URLs)."""
    out, cur = {}, {}
    for line in gitmodules.splitlines() + ["[end]"]:
        line = line.strip()
        if line.startswith("["):
            if cur.get("path") and cur.get("url"):
                u = cur["url"]
                if u.startswith(("../", "./")):
                    full = os.path.normpath(os.path.join("/" + repo, u))
                else:
                    full = "/" + "/".join(u.split("://", 1)[-1].split("/")[1:])
                full = full[:-4] if full.endswith(".git") else full
                parts = full.strip("/").split("/")
                if len(parts) >= 2:
                    out[cur["path"]] = "/".join(parts[-2:])
            cur = {}
        elif "=" in line:
            k, v = (x.strip() for x in line.split("=", 1))
            cur[k] = v
    return out


def monorepo_sources(repo: str, path: str, context: str, gitmodules: str, update: str) -> list[dict]:
    """The submodules a monorepo project depends on: the one its build context is in, and the one its IaC
    root is in (a config repo inside the monorepo)."""
    subs = submodules(gitmodules, repo)
    ctx = os.path.normpath(os.path.join(path, context))
    out = []
    for p, r in sorted(subs.items()):
        if ctx == p or ctx.startswith(p + "/") or path == p or path.startswith(p + "/"):
            out.append({"path": p, "repo": r, "branch": "main", "update": update})
    return out


def wrap_new(a, root: Path, token: str, hook_secret: str):
    code, src = cicd.api("GET", a.server, f"/repos/{a.source}", token)
    if code != 200:
        sys.exit(f"cannot read {a.source}: {code}")
    branch = a.branch or src.get("default_branch") or "main"
    iac = f"{a.org}/{a.app}"
    code, _ = cicd.api("GET", a.server, f"/repos/{iac}", token)
    if code == 404:
        code, out = cicd.api("POST", a.server, f"/orgs/{a.org}/repos", token, {
            "name": a.app, "private": bool(src.get("private")), "auto_init": False, "default_branch": "main",
            "description": f"How {a.source} is built and deployed (cicd-ref-arch, wrapped)"})
        if code not in (200, 201):
            sys.exit(f"could not create {iac}: {code} {out}")
        print(f"created {iac}")
    elif code == 200:
        code, branches = cicd.api("GET", a.server, f"/repos/{iac}/branches", token)
        if branches:
            sys.exit(f"{iac} exists and has content: wrap only fills an empty repo")

    user = os.environ.get("BOT", "cicd-bot")
    auth = "AUTHORIZATION: basic " + base64.b64encode(f"{user}:{token}".encode()).decode()
    work = Path(tempfile.mkdtemp(prefix=f"wrap-{a.app}-"))
    try:
        def git(*args):
            return subprocess.run(["git", "-c", f"http.extraHeader={auth}", "-c", "user.name=cicd-bot",
                                   "-c", "user.email=cicd-bot@noreply.invalid", "-C", str(work), *args],
                                  capture_output=True, text=True, check=True).stdout.strip()
        git("init", "-q", "-b", "main")
        git("submodule", "add", "-q", "-b", branch, f"{a.server.rstrip('/')}/{a.source}.git", "src")
        # a relative URL: the forge's own address (and any mirror of both repos) resolves it
        git("config", "-f", ".gitmodules", "submodule.src.url", os.path.relpath(f"/{a.source}.git", f"/{iac}"))
        d = detect(work / "src")
        made = generate(work, a.app, a.source, d, a.update)
        sha = git("-C", "src", "rev-parse", "HEAD")
        git("add", "-A")
        msg = [f"wrap {a.source} ({d['kind']})", "",
               f"Source-Repo: {a.source}", f"Source-Branch: {branch}", f"Source-Commit: {sha}"]
        if a.requested_by:
            msg.append(f"Requested-by: {a.requested_by}")
        git("commit", "-q", "-m", "\n".join(msg))
        git("push", "-q", f"{a.server.rstrip('/')}/{iac}.git", "HEAD:refs/heads/main")
        print(f"pushed {iac}: src -> {a.source}@{sha[:7]}; {', '.join(made)}")
    finally:
        shutil.rmtree(work, ignore_errors=True)
    if a.hook_url:
        hooks(a.server, token, a.hook_url, hook_secret, [iac, a.source], Path(a.root))
    write_tenant(root, a, {"mode": "wrapped", "repo": iac, "path": ".",
                           "sources": [{"path": "src", "repo": a.source, "branch": branch, "update": a.update}]},
                 f"Wrapped by tools/wrap.py: built and deployed from {iac}, code from {a.source}")


def enroll_monorepo(a, root: Path, token: str, hook_secret: str):
    """A project of a monorepo: the IaC root is a.path in a.repo; its sources are the submodules it builds from.
    The monorepo holds IaC roots, so it is one of CI/CD's repos (tenants/_writable.yaml); a developer's
    monorepo is wrapped project by project instead."""
    if not cicd.writable(root, a.repo):
        sys.exit(f"{a.repo} is a developer's repo: CI/CD writes only to its own (tenants/_writable.yaml). Wrap it instead (--mode wrapped)")
    code, _ = cicd.api("GET", a.server, f"/repos/{a.repo}", token)
    if code != 200:
        sys.exit(f"cannot read {a.repo}: {code}")
    code, gm = cicd.api("GET", a.server, f"/repos/{a.repo}/raw/.gitmodules", token)
    gm = gm if code == 200 and isinstance(gm, str) else ""
    code, cfg = cicd.api("GET", a.server, f"/repos/{a.repo}/raw/{a.path}/cicd.yaml", token)
    context = "."
    if code == 200 and isinstance(cfg, str):
        context = ((yaml.safe_load(cfg) or {}).get("spec", {}).get("build") or {}).get("context", ".")
    else:
        # the IaC root may be inside a config submodule: read it through that submodule's repo
        for p, r in submodules(gm, a.repo).items():
            if a.path.startswith(p + "/"):
                c2, cfg = cicd.api("GET", a.server, f"/repos/{r}/raw/{a.path[len(p) + 1:]}/cicd.yaml", token)
                if c2 == 200 and isinstance(cfg, str):
                    context = ((yaml.safe_load(cfg) or {}).get("spec", {}).get("build") or {}).get("context", ".")
                break
    sources = monorepo_sources(a.repo, a.path, context, gm, a.update)
    print(f"{a.repo}:{a.path}, context {context}: sources {', '.join(x['path'] + ' ' + x['repo'] for x in sources) or 'none'}")
    if a.hook_url:
        hooks(a.server, token, a.hook_url, hook_secret, [a.repo] + [x["repo"] for x in sources], Path(a.root))
    write_tenant(root, a, {"mode": "monorepo", "repo": a.repo, "path": a.path, "sources": sources},
                 f"A project of the monorepo {a.repo} at {a.path}")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--app", required=True)
    ap.add_argument("--mode", default="wrapped", choices=["wrapped", "monorepo", "prebuilt"])
    ap.add_argument("--image", help="prebuilt: the image to follow, repository:tag")
    ap.add_argument("--source", help="wrapped: owner/name of the source repo on this forge")
    ap.add_argument("--repo", help="monorepo: owner/name of the monorepo")
    ap.add_argument("--path", help="monorepo: the project's IaC root in it, e.g. apps/api")
    ap.add_argument("--branch", help="the source branch that maps to the IaC repo's dev branch (default: its default)")
    ap.add_argument("--update", default="follow", choices=cicd.UPDATES)
    ap.add_argument("--org", default="ffwf-iac")
    ap.add_argument("--tenant", default="ffwf")
    ap.add_argument("--cluster", action="append", default=[])
    ap.add_argument("--hook-url", default=os.environ.get("CICD_HOOK_URL", ""))
    ap.add_argument("--requested-by", default="")
    ap.add_argument("--approved", action="store_true", help="enroll as approved (an admin running this); default pending")
    ap.add_argument("--server", default=os.environ.get("FORGEJO_URL", "https://forge.goblincorps.com"))
    ap.add_argument("--root", default=str(ROOT), help="the platform repo checkout to write tenants/<app>.yaml into")
    a = ap.parse_args()
    if not cicd.re.fullmatch(r"[a-z0-9][a-z0-9-]{0,62}", a.app):
        sys.exit("bad app name")
    token = os.environ.get("FORGEJO_TOKEN") or sys.exit("FORGEJO_TOKEN is not set")
    hook_secret = os.environ.get("CICD_HOOK_SECRET", "")
    if a.hook_url and not hook_secret:
        sys.exit("CICD_HOOK_SECRET is not set (needed with --hook-url)")
    root = Path(a.root)
    if (root / "tenants" / f"{a.app}.yaml").exists():
        sys.exit(f"{a.app} is already enrolled")
    if a.mode == "wrapped":
        if not a.source:
            sys.exit("--source is needed")
        wrap_new(a, root, token, hook_secret)
    elif a.mode == "prebuilt":
        if not a.image:
            sys.exit("--image is needed")
        wrap_prebuilt(a, root, token, hook_secret)
    else:
        if not (a.repo and a.path):
            sys.exit("--repo and --path are needed")
        enroll_monorepo(a, root, token, hook_secret)


if __name__ == "__main__":
    main()
