#!/usr/bin/env python3
"""wrap: enroll an app in wrapped mode (docs/enrollment.md). Creates the IaC repo <org>/<app>, with the
source repo as the submodule src/, a Dockerfile, cicd.yaml and deploy/ generated for it, and writes
tenants/<app>.yaml here. Nothing is pushed to the source repo.

  FORGEJO_TOKEN=<owner of the IaC org> [CICD_HOOK_SECRET=...] tools/wrap.py --app mabel --source ffwf/mabel-src \
    [--branch main] [--update follow|pin] [--org ffwf-iac] [--tenant ffwf] [--cluster c-local] \
    [--hook-url https://<dashboard>/hooks/forge] [--requested-by john] [--approved]

The Dockerfile: the source's own if it has one (build context src/, dockerfile src/Dockerfile);
otherwise one picked from what the source holds (templates/iac/dockerfiles): a static site
(index.html in ., public/, site/, dist/ or docs/), Python (requirements.txt or pyproject.toml, with
main.py or app.py), Node (package.json with a start script). None of these: no Dockerfile, and
intake's `dockerfile` check says what to add, in the IaC repo.
"""
from __future__ import annotations

import argparse
import base64
import json
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(HERE))
import cicd    # noqa: E402
import intake  # noqa: E402

TEMPLATES = ROOT / "templates" / "iac"


def detect(src: Path) -> dict:
    """What to build the source with: {kind, port, dockerfile text or None, context, dockerfile path, run_as}."""
    if (src / "Dockerfile").is_file():
        return {"kind": "own", "port": intake.exposed_port(src / "Dockerfile"), "text": None,
                "context": "src", "dockerfile": "src/Dockerfile"}
    for site in (".", "public", "site", "dist", "docs"):
        if (src / site / "index.html").is_file():
            t = (TEMPLATES / "dockerfiles/static.Dockerfile").read_text().replace("{site}", "./" if site == "." else f"{site}/")
            return {"kind": "static", "port": 8080, "text": t, "context": "src", "dockerfile": "Dockerfile", "run_as": 101}
    if (src / "requirements.txt").is_file() or (src / "pyproject.toml").is_file():
        entry = next((e for e in ("main.py", "app.py", "server.py") if (src / e).is_file()), None)
        if entry:
            install = "-r requirements.txt" if (src / "requirements.txt").is_file() else "."
            t = (TEMPLATES / "dockerfiles/python.Dockerfile").read_text().replace("{entry}", entry).replace("{install}", install)
            return {"kind": "python", "port": 8000, "text": t, "context": "src", "dockerfile": "Dockerfile"}
    if (src / "package.json").is_file():
        try:
            pkg = json.loads((src / "package.json").read_text())
        except ValueError:
            pkg = {}
        if (pkg.get("scripts") or {}).get("start"):
            t = (TEMPLATES / "dockerfiles/node.Dockerfile").read_text()
            return {"kind": "node", "port": 3000, "text": t, "context": "src", "dockerfile": "Dockerfile"}
    return {"kind": "none", "port": intake.DEFAULT_PORT, "text": None, "context": "src", "dockerfile": "Dockerfile"}


def generate(work: Path, app: str, source: str, d: dict, update: str) -> list[str]:
    """Write the IaC root's files for a detected source. Returns what was written."""
    out = []
    if d["text"]:
        (work / "Dockerfile").write_text(d["text"])
        out.append(f"Dockerfile ({d['kind']})")
    cfg = intake.default_cicd(app, "main", d["port"], context=d["context"], dockerfile=d["dockerfile"])
    (work / "cicd.yaml").write_text(f"# generated by tools/wrap.py for {source} ({d['kind']}): this repo owns it, edit it here\n"
                                    + yaml.safe_dump(cfg, sort_keys=False))
    out.append("cicd.yaml")
    (work / "deploy").mkdir(exist_ok=True)
    files = intake.default_deploy(app, d["port"])
    if d.get("run_as"):
        dep = yaml.safe_load(files["deployment.yaml"])
        sc = dep["spec"]["template"]["spec"]["securityContext"]
        sc["runAsUser"] = sc["runAsGroup"] = d["run_as"]
        files["deployment.yaml"] = yaml.safe_dump(dep, sort_keys=False)
    for name, text in files.items():
        (work / "deploy" / name).write_text(text)
    out.append("deploy/")
    how = "each push to its default branch is committed here and deploys dev" if update == "follow" \
        else "each push opens a PR here; merging it deploys"
    (work / "README.md").write_text((TEMPLATES / "README.md").read_text().format(
        app=app, source=source, update=update, update_how=how))
    out.append("README.md")
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--app", required=True)
    ap.add_argument("--source", required=True, help="owner/name of the source repo on this forge")
    ap.add_argument("--branch", help="the source branch that maps to the IaC repo's dev branch (default: its default)")
    ap.add_argument("--update", default="follow", choices=cicd.UPDATES)
    ap.add_argument("--org", default="ffwf-iac")
    ap.add_argument("--tenant", default="ffwf")
    ap.add_argument("--cluster", action="append", default=[])
    ap.add_argument("--hook-url", default=os.environ.get("CICD_HOOK_URL", ""))
    ap.add_argument("--requested-by", default="")
    ap.add_argument("--approved", action="store_true", help="enroll as approved (an admin running this); default pending")
    ap.add_argument("--server", default=os.environ.get("FORGEJO_URL", "https://forge.goblincorps.com"))
    ap.add_argument("--root", default=str(ROOT), help="the platform repo checkout to write tenants/<app>.yaml into")
    a = ap.parse_args()
    if not cicd.re.fullmatch(r"[a-z0-9][a-z0-9-]{0,62}", a.app):
        sys.exit("bad app name")
    token = os.environ.get("FORGEJO_TOKEN") or sys.exit("FORGEJO_TOKEN is not set")
    user = os.environ.get("BOT", "cicd-bot")
    hook_secret = os.environ.get("CICD_HOOK_SECRET", "")
    if a.hook_url and not hook_secret:
        sys.exit("CICD_HOOK_SECRET is not set (needed with --hook-url)")
    root = Path(a.root)
    if (root / "tenants" / f"{a.app}.yaml").exists():
        sys.exit(f"{a.app} is already enrolled")

    code, src = cicd.api("GET", a.server, f"/repos/{a.source}", token)
    if code != 200:
        sys.exit(f"cannot read {a.source}: {code}")
    branch = a.branch or src.get("default_branch") or "main"
    iac = f"{a.org}/{a.app}"
    code, _ = cicd.api("GET", a.server, f"/repos/{iac}", token)
    if code == 404:
        code, out = cicd.api("POST", a.server, f"/orgs/{a.org}/repos", token, {
            "name": a.app, "private": bool(src.get("private")), "auto_init": False, "default_branch": "main",
            "description": f"How {a.source} is built and deployed (cicd-ref-arch, wrapped)"})
        if code not in (200, 201):
            sys.exit(f"could not create {iac}: {code} {out}")
        print(f"created {iac}")
    elif code == 200:
        code, branches = cicd.api("GET", a.server, f"/repos/{iac}/branches", token)
        if branches:
            sys.exit(f"{iac} exists and has content: wrap only fills an empty repo")

    auth = "AUTHORIZATION: basic " + base64.b64encode(f"{user}:{token}".encode()).decode()
    work = Path(tempfile.mkdtemp(prefix=f"wrap-{a.app}-"))
    try:
        def git(*args):
            return subprocess.run(["git", "-c", f"http.extraHeader={auth}", "-c", "user.name=cicd-bot",
                                   "-c", "user.email=cicd-bot@noreply.invalid", "-C", str(work), *args],
                                  capture_output=True, text=True, check=True).stdout.strip()
        git("init", "-q", "-b", "main")
        git("submodule", "add", "-q", "-b", branch, f"{a.server.rstrip('/')}/{a.source}.git", "src")
        # a relative URL: the forge's own address (and any mirror of both repos) resolves it
        rel = os.path.relpath(f"/{a.source}.git", f"/{iac}")
        git("config", "-f", ".gitmodules", "submodule.src.url", rel)
        d = detect(work / "src")
        made = generate(work, a.app, a.source, d, a.update)
        sha = git("-C", "src", "rev-parse", "HEAD")
        git("add", "-A")
        msg = [f"wrap {a.source} ({d['kind']})", "",
               f"Source-Repo: {a.source}", f"Source-Branch: {branch}", f"Source-Commit: {sha}"]
        if a.requested_by:
            msg.append(f"Requested-by: {a.requested_by}")
        git("commit", "-q", "-m", "\n".join(msg))
        git("push", "-q", f"{a.server.rstrip('/')}/{iac}.git", "HEAD:refs/heads/main")
        print(f"pushed {iac}: src -> {a.source}@{sha[:7]}; {', '.join(made)}")
    finally:
        shutil.rmtree(work, ignore_errors=True)

    if a.hook_url:
        for repo in (iac, a.source):
            hook = {"type": "forgejo", "active": True, "events": ["push"], "branch_filter": "*",
                    "config": {"url": a.hook_url, "content_type": "json", "secret": hook_secret}}
            code, hooks = cicd.api("GET", a.server, f"/repos/{repo}/hooks", token)
            same = [h for h in (hooks if code == 200 else []) if (h.get("config") or {}).get("url") == a.hook_url]
            if same:
                code, _ = cicd.api("PATCH", a.server, f"/repos/{repo}/hooks/{same[0]['id']}", token, {
                    "active": True, "events": ["push"], "branch_filter": "*", "config": hook["config"]})
            else:
                code, _ = cicd.api("POST", a.server, f"/repos/{repo}/hooks", token, hook)
            print(f"webhook on {repo}: {code}")

    spec = {"kind": "App", "mode": "wrapped", "tenant": a.tenant, "repo": iac, "path": ".",
            "sources": [{"path": "src", "repo": a.source, "branch": branch, "update": a.update}],
            "clusters": a.cluster or ["c-local"], "enrolled": cicd.now_utc().date().isoformat()}
    if not a.approved:
        spec["status"] = "pending"
    if a.requested_by:
        spec["requestedBy"] = a.requested_by
    t = {"apiVersion": cicd.API, "kind": "Tenant", "metadata": {"name": a.app}, "spec": spec}
    cicd.tenant_spec(t)   # checks it
    (root / "tenants").mkdir(exist_ok=True)
    (root / "tenants" / f"{a.app}.yaml").write_text(
        f"# Wrapped by tools/wrap.py (docs/enrollment.md): built and deployed from {iac}, code from {a.source}.\n"
        + yaml.safe_dump(t, sort_keys=False))
    print(f"wrote tenants/{a.app}.yaml ({'approved' if a.approved else 'pending'}): commit and push it")


if __name__ == "__main__":
    main()
